const AgentRunModelOutputSchema = z.object({
  output: z.string().default(""),
  progress: z.number().min(0).max(100).nullable().default(null),
  widgetUpdates: z.array(z.object({ id: z.string(), value: z.any() })).default([]),
});

const AGENT_RUN_RESPONSE_SCHEMA: Schema = {
  type: Type.OBJECT,
  properties: {
    output: { type: Type.STRING, description: "Execution summary / findings for this run" },
    progress: {
      type: Type.NUMBER,
      nullable: true,
      description: "Your genuine 0-100 progress estimate for the card, or null to leave progress unchanged",
    },
    widgetUpdates: {
      type: Type.ARRAY,
      description: "Updates to apply to specific widgets, referenced by their existing id. Omit widgets you did not change.",
      items: {
        type: Type.OBJECT,
        properties: {
          id: { type: Type.STRING },
          value: {},
        },
        required: ["id", "value"],
      },
    },
  },
  required: ["output"],
};

const RUN_ERROR_RETRYABLE: Record<RunErrorCode, boolean> = {
  invalid_input: false,
  provider_error: true,
  timeout: true,
  rate_limited: true,
  budget_exhausted: false,
  internal: true,
  aborted: false,
};

function makeRunError(code: RunErrorCode, message: string): RunErrorInfo {
  return { code, message, retryable: RUN_ERROR_RETRYABLE[code] };
}

function classifyProviderError(err: unknown): RunErrorInfo {
  if (err instanceof ApiError) {
    if (err.status === 429) {
      return makeRunError("rate_limited", "Gemini API rate limit exceeded.");
    }
    if (err.status === 402) {
      return makeRunError("budget_exhausted", "Gemini API billing/quota exhausted.");
    }
    if (err.status >= 500) {
      return makeRunError("provider_error", `Gemini API server error (${err.status}).`);
    }
    return makeRunError("provider_error", err.message || "Gemini API request failed.");
  }
  return makeRunError("internal", err instanceof Error ? err.message : "Unknown error executing agent run.");
}

function mergeWidgetUpdates(
  original: InteractiveWidget[],
  updates: Array<{ id: string; value: unknown }>
): InteractiveWidget[] {
  if (updates.length === 0) return original;
  const updateMap = new Map(updates.map((u) => [u.id, u.value]));
  return original.map((w) =>
    updateMap.has(w.id) ? { ...w, value: updateMap.get(w.id) as InteractiveWidget["value"] } : w
  );
}

const AGENT_RUN_TIMEOUT_MS = 60_000;

/**
 * In-process idempotency cache for /agent-run, keyed by Idempotency-Key
 * (falls back to runId). Small LRU (~200 entries, 10 minute TTL) so a
 * lease-reclaim retry doesn't re-charge/re-run the same card execution.
 *
 * NOTE: this cache is per-instance/in-memory only. If the server ever runs
 * as more than one process/instance, a retry landing on a different
 * instance will not see the cached result — this needs a shared store
 * (Redis, Firestore, etc.) to be effective at that point.
 */
const IDEMPOTENCY_CACHE_MAX = 200;
const IDEMPOTENCY_TTL_MS = 10 * 60 * 1000;

interface IdempotencyEntry {
  value: AgentRunApiResponse;
  expiresAt: number;
}

const idempotencyCache = new Map<string, IdempotencyEntry>();

function getCachedRun(key: string): AgentRunApiResponse | undefined {
  const entry = idempotencyCache.get(key);
  if (!entry) return undefined;
  if (Date.now() > entry.expiresAt) {
    idempotencyCache.delete(key);
    return undefined;
  }
  // Refresh recency for LRU eviction.
  idempotencyCache.delete(key);
  idempotencyCache.set(key, entry);
  return entry.value;
}

function setCachedRun(key: string, value: AgentRunApiResponse): void {
  if (idempotencyCache.size >= IDEMPOTENCY_CACHE_MAX) {
    const oldestKey = idempotencyCache.keys().next().value;
    if (oldestKey !== undefined) idempotencyCache.delete(oldestKey);
  }
  idempotencyCache.set(key, { value, expiresAt: Date.now() + IDEMPOTENCY_TTL_MS });
}

async function executeAgentRun(request: AgentRunRequest): Promise<AgentRunApiResponse> {
  const ai = getGeminiClient();
  const originalWidgets = (request.widgets ?? []) as InteractiveWidget[];

  if (!ai) {
    return {
      ok: true,
      output: `[Agent Output Simulator] Processed task "${request.cardTitle}". No GEMINI_API_KEY configured — this is a simulated response; progress and widgets are left unchanged.`,
      suggestedProgress: null,
      updatedWidgets: originalWidgets,
      usage: { model: MODELS.agentRun, estimatedTokens: 0 },
    };
  }

  const controller = new AbortController();
  const timeoutHandle = setTimeout(() => controller.abort(), AGENT_RUN_TIMEOUT_MS);

  try {
    const upstreamContext = request.upstream.length
      ? `\n\nUpstream card outputs:\n${request.upstream.map((u) => `- ${u.title} (${u.cardId}): ${u.output}`).join("\n")}`
      : "";
    const goalContext = request.goal
      ? `\n\nParent goal: "${request.goal.title}" — desired outcome: "${request.goal.outcome}"`
      : "";

    const promptText = `Card Title: ${request.cardTitle}
Card Description: ${request.cardDescription}
Task Prompt: ${request.prompt || "Execute routine analysis and optimize parameters."}${upstreamContext}${goalContext}

Current widgets: ${JSON.stringify(originalWidgets)}

Execute this task and report your genuine findings and progress assessment.`;

    const response = await ai.models.generateContent({
      model: request.model || MODELS.agentRun,
      contents: promptText,
      config: {
        systemInstruction:
          request.systemPrompt ||
          "You are an autonomous AI worker executing a kanban card task. Report your honest assessment of progress — do not assume the task is complete.",
        responseMimeType: "application/json",
        responseSchema: AGENT_RUN_RESPONSE_SCHEMA,
        abortSignal: controller.signal,
      },
    });

    let parsed: z.infer<typeof AgentRunModelOutputSchema>;
    try {
      parsed = parseModelJson(response.text, AgentRunModelOutputSchema, "agent-run");
    } catch (err) {
      if (err instanceof ModelResponseError) {
        console.error(`[agent-run] invalid model response: ${err.raw}`);
        return { ok: false, error: makeRunError("provider_error", "Model returned an invalid response.") };
      }
      throw err;
    }

    return {
      ok: true,
      output: parsed.output || "Task executed successfully.",
      suggestedProgress: parsed.progress,
      updatedWidgets: mergeWidgetUpdates(originalWidgets, parsed.widgetUpdates),
      usage: {
        model: request.model || MODELS.agentRun,
        estimatedTokens: response.usageMetadata?.totalTokenCount ?? 0,
      },
    };
  } catch (err) {
    if (controller.signal.aborted) {
      return { ok: false, error: makeRunError("timeout", `Agent run exceeded the ${AGENT_RUN_TIMEOUT_MS / 1000}s execution budget.`) };
    }
    return { ok: false, error: classifyProviderError(err) };
  } finally {
    clearTimeout(timeoutHandle);
  }
}

export async function callAgentRun(request: AgentRunRequest, idempotencyKey: string): Promise<AgentRunApiResponse> {
  const cached = getCachedRun(idempotencyKey);
  if (cached) return cached;

  const result = await executeAgentRun(request);
  setCachedRun(idempotencyKey, result);
  return result;
}

