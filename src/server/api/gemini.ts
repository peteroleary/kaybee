/**
 * Returns a PlanProposal-compatible shape (flat `{summary, newLists, newCards,
 * suggestedAgents, notes}`) so both this and the orchestrator's `proposal`
 * feed the same client-side normalizer (`materializePlan`).
 */
export async function callGoalDecomposition(
  goal: { title: string; description: string; outcome: string },
  currentBoard?: any
): Promise<PlanProposal> {
  const ai = getGeminiClient();

  if (!ai) {
    return buildGoalDecompositionFallback(goal);
  }

  const capabilities = AGENT_CAPABILITY_IDS.join(" | ");

  const systemInstruction = `You are the Goal Decomposition Agent for KayBee Kanban Board.
Your job is to break down high-level user goals into actionable lists and tasks that can be autonomously executed by AI agents.

Given a goal with title, description, and desired outcome, return a structured JSON object matching this schema:
{
  "summary": "Brief explanation of the decomposition strategy",
  "newLists": [
    {
      "title": "string",
      "listType": "kanban",
      "color": "string (e.g. indigo, purple, emerald, amber, rose, cyan)",
      "cards": [
        {
          "title": "Action-oriented task name",
          "description": "What needs to be done",
          "entityType": "task" | "human" | "agent",
          "priority": "low" | "medium" | "high" | "urgent",
          "tags": ["string"],
          "assignedAgentType": "(optional) one of: ${capabilities}"
        }
      ]
    }
  ],
  "newCards": [],
  "suggestedAgents": [${capabilities}],
  "notes": []
}

Return 3-5 lists representing workflow stages (e.g., Planning, Development, Testing, Deployment), each with 2-4 cards.
Always return valid JSON matching this schema.`;

  const response = await ai.models.generateContent({
    model: MODELS.goalDecompose,
    contents: `Goal Title: "${goal.title}"
Goal Description: "${goal.description}"
Desired Outcome: "${goal.outcome}"

Current Board Context: ${currentBoard ? JSON.stringify({ name: currentBoard.name, existingLists: currentBoard.lists?.length }) : "No board context"}`,
    config: {
      systemInstruction,
      responseMimeType: "application/json",
    },
  });

  return parseModelJson(response.text, PlanProposalSchema, "goal-decompose");
}
